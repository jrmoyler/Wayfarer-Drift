// Generates dist/sw.js: a content-versioned, cache-first service worker that
// precaches the whole build atomically so offline play never mixes versions.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const dist = new URL('../dist/', import.meta.url).pathname;
const files = [];
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (name !== 'sw.js') files.push(p);
  }
};
walk(dist);
const hash = createHash('sha256');
let bytes = 0;
for (const f of files.sort()) {
  const buf = readFileSync(f);
  bytes += buf.length;
  hash.update(f).update(buf);
}
const version = hash.digest('hex').slice(0, 12);
const urls = ['./', ...files.map((f) => './' + relative(dist, f).split('\\').join('/'))];

const sw = `/* Generated by scripts/sw.mjs */
const CACHE = 'wayfarer-${version}';
const URLS = ${JSON.stringify(urls)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(URLS)));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))));
});
self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET') return;
  const url = new URL(e.request.url);
  if (url.origin !== location.origin) return;
  e.respondWith(
    caches.match(e.request, { ignoreSearch: url.pathname.endsWith('/') || url.pathname.endsWith('index.html') })
      .then((hit) => hit || fetch(e.request)),
  );
});
`;
writeFileSync(join(dist, 'sw.js'), sw);
console.log(`sw.js: ${urls.length} files, ${(bytes / 1048576).toFixed(1)} MB, version ${version}`);
